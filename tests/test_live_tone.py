"""Тон ефіру й радіо (04.11, власник): без хибних «на щастя», без порожніх заспокоювань."""
from app.live import scrub


def test_no_false_joy():
    assert scrub("На щастя, жодна ціль не зникла з мапи.") == ""
    assert scrub("Шахед біля Чугуєва. На щастя, жодна ціль не зникла з мапи.") == "Шахед біля Чугуєва."
    assert scrub("На щастя, шахед летить на Харків.") == "Шахед летить на Харків."
    assert scrub("На щастя, шахед зник з мапи.") == "На щастя, шахед зник з мапи."


def test_no_empty_reassurance():
    assert scrub("Ситуація під контролем, слідкуйте за оновленнями!") == ""
    assert scrub("Шахед на Чугуїв. Ситуація під контролем.") == "Шахед на Чугуїв."
    assert scrub("Дрон-розвідник, на жаль, зник.") == "Дрон-розвідник зник."
