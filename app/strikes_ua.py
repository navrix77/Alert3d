class UaStrikes:
    def __init__(self, gaz=None) -> None:
        self.gaz = gaz
        self.events: list[dict] = []
        self.seen: set[str] = set()
        self._extra: list[str] = []

    def locate(self, name: str):
        low = name.lower()
        for stem, (n, la, lo) in RU_CITIES.items():
            if low.startswith(stem):
                return n, la, lo
        if self.gaz:
            ids = self.gaz.lookup(name.split()[0]) if " " not in name else (self.gaz.lookup_bigram(*name.split()[:2]) or self.gaz.lookup(name.split()[0]))
            if ids:
                p = max((self.gaz.places[i] for i in ids), key=lambda q: q.pop)
                return p.name, p.lat, p.lon
        return None

    def parse(self, text: str) -> list[dict]:
        if not re.search(r"уражен|урази|вразил|знищен", text.lower()) or "оперативна інформація" in text.lower():
            return []
        out = []
        for m in BULLET.finditer(text):
            obj, place = m.group(1).strip(" .:-—"), m.group(2)
            lo_obj = obj.lower()
            what = next((label for k, label in WHAT if k in lo_obj), None)
            if not what:
                continue
            # «Склад», «Пункт», «Чому» з великої на початку наступного рядка/речення — не населений пункт (05.11: точка «Склад» на мапі)
            if re.match(r"(?:склад|пункт|завод|район|област|чому|наслідк|за\b|це\b|тот\b|ар\b|зргк|зрк|рлс|нпз)", place.lower()):
                continue
            loc = self.locate(place)
            if not loc:
                continue
            out.append({"what": what, "detail": obj[:140], "place": loc[0], "lat": loc[1], "lon": loc[2], **({"wb": True} if what == "Склад Wildberries" else {})})
        return out

    def parse_astra(self, text: str) -> list[dict]:
        low = text.lower().replace("ё", "е")
        if not ATTACK.search(low) or "всу" in low and "обстрел" in low:
            return []
        if not re.search(r"беспилотн|бпла|дрон", low):
            return []  # лише атаки дронів (не артобстріли)
        seen, out = set(), []
        tx = text.replace("ё", "е")
        head_end = len(tx.split("\n", 1)[0])  # заголовок (перший рядок) — там завжди місце події
        for wm in re.finditer(r"(?<![а-яё])([А-ЯЁ][а-яё]+(?:-[а-яА-ЯЁё]+){0,2})", tx):
            w = wm.group(1)
            lw = w.lower()
            # «в Белгородской области», «Ракитянского округа»: це назва регіону, а не міста; крапку на місто не ставимо (ASTRA 04.11)
            if re.match(r"\s+(?:област|округ|район|край|республик)", tx[wm.end():wm.end() + 12].lower()) or re.search(r"(?:ой|ого|ому|ая|ую|ское|ского|ских|ские)$", lw):
                continue
            # місто лише згадане, а не атаковане: «снабжает Москву», «в 180 км от Москвы», «как и Рязань ранее» (05.11: вогонь на Москві
            # з поста про Рязанський НПЗ). Поза заголовком місто беремо лише з речення, де є сама атака/пожежа, і не в такому контексті.
            if wm.start() > head_end:
                s0 = max(tx.rfind(".", 0, wm.start()), tx.rfind("\n", 0, wm.start())) + 1
                s1 = min([i for i in (tx.find(".", wm.end()), tx.find("\n", wm.end())) if i >= 0] or [len(tx)])
                sent = tx[s0:s1].lower()
                before = tx[s0:wm.start()].lower()
                if not ATTACK.search(sent) and not re.search(r"горит|горел|пожар|взрыв|удар|прилет|поражен|атак", sent):
                    continue
                if re.search(r"(?<![а-я])(?:снабжа\w*|поставля\w*|поставщик\w*|потребител\w*|для|км от|от|до|направлени\w*|в сторону|как и|ранее|прошл\w*|аналогичн\w*)\s+\S*$", before):
                    continue
            hit = None
            for form, key in RU_FORMS.items():
                if lw.startswith(form):
                    hit = RU_CITIES.get(key)
                    break
            if not hit:
                hit = next((v for k, v in RU_EXTRA.items() if lw.startswith(k)), None)
            if hit and hit[0] not in seen:
                seen.add(hit[0])
                wb = bool(WB_RE.search(text))
                whats = ([("Логістичний центр Wildberries" if re.search(r"логіст|логист", low) else "Склад Wildberries")] if wb else []) + [lab for k, lab in WHAT_RU if re.search(r"(?<![а-яе])" + re.escape(k), low) and not (wb and lab in ("Склад", "Логістичний центр"))]  # з початку слова: «транспортное» не «порт»
                whats = list(dict.fromkeys(whats))
                if any(w not in ("Завод", "Підприємство", "Склад") for w in whats):
                    whats = [w for w in whats if w not in ("Завод", "Підприємство", "Склад")]  # «завод» у тексті про НПЗ — той самий об'єкт, не окремий
                whats = whats[:3] or ["Атака дронів"]
                out.append({"what": whats[0], "detail": re.sub(r"\s+", " ", text.strip())[:320], "place": hit[0], "lat": hit[1], "lon": hit[2], "src": "ASTRA", **({"wb": True} if wb else {})})
                self._extra = whats[1:]
            if len(out) >= 3:
                break
        # одне місто, кілька уражених об'єктів (НПЗ і склад Wildberries): окрема подія, а отже й окремий вогник, на кожен
        if len(out) == 1 and getattr(self, "_extra", None):
            for w in self._extra[:3]:
                ev = {**out[0], "what": w}
                ev["wb"] = True if "Wildberries" in w else ev.pop("wb", None) and False
                if not ev["wb"]:
                    ev.pop("wb")
                out.append(ev)
        self._extra = []
        return out

    def ingest(self, text: str, ts: float, link: str | None, src: str) -> int:
        """Будь-який з моніторингових каналів (укр./рос. текст): «НПЗ у Рязані під атакою БпЛА», «логістичний центр Wildberries» → вогники.
        Один об'єкт з різних каналів не дублюється: те саме місце й об'єкт у межах 3 годин — одна подія."""
        n = 0
        try:
            for ev in self.parse_astra(text):
                if any(e["place"] == ev["place"] and e["what"] == ev["what"] and abs(e["t"] - ts) < 10800 for e in self.events):
                    continue
                ev.update(src=src, t=ts, link=link)
                self.events.append(ev)
                n += 1
        except Exception as e:  # noqa: BLE001
            log.warning("ingest: %s", e)
        return n

    def state(self) -> list[dict]:
        now = time.time()
        return [e for e in self.events if now - e["t"] < 72 * 3600]

    async def run(self) -> None:
        async with httpx.AsyncClient(timeout=20, headers=UA, follow_redirects=True) as cli:
            while True:
                try:
                    for ch, fn, src in ((CHANNEL, self.parse, "Генштаб ЗСУ"), (ASTRA, self.parse_astra, "ASTRA")):
                        r = await cli.get(f"https://t.me/s/{ch}")
                        for mid, ts, text in parse_page(r.text):
                            link = f"https://t.me/{ch}/{mid}"
                            if link in self.seen:
                                continue
                            self.seen.add(link)
                            for ev in fn(text):
                                ev.setdefault("src", src)
                                ev.update(t=ts, link=link)
                                self.events.append(ev)
                    for ch in dict.fromkeys(EXTRA_CHANNELS + [c.strip().lstrip("@") for c in os.getenv("STRIKE_CHANNELS", "").split(",") if c.strip()]):
                        try:
                            r = await cli.get(f"https://t.me/s/{ch}")
                            for mid, ts, text in parse_page(r.text):
                                link = f"https://t.me/{ch}/{mid}"
                                if link in self.seen:
                                    continue
                                self.seen.add(link)
                                self.ingest(text, ts, link, "@" + ch)
                        except Exception as e:  # noqa: BLE001
                            log.debug("strikes %s: %s", ch, e)
                    self.events = self.state()
                except Exception as e:  # noqa: BLE001
                    log.warning("strikes: %s", e)
                await asyncio.sleep(300)
