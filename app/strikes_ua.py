class UaStrikes:
    def __init__(self, gaz=None) -> None:
        self.gaz = gaz
        self.events: list[dict] = []
        self.seen: set[str] = set()

    def locate(self, name: str):
        low = name.lower()
        for stem, (n, la, lo) in RU_CITIES.items():
            if low.startswith(stem):
                return n, la, lo
        if self.gaz:
            ids = self.gaz.lookup(name.split()[0]) if " " not in name else (self.gaz.lookup_bigram(*name.split()[:2]) or self.gaz.lookup(name.split()[0]))
            if ids:
                p = max((self.gaz.places[i] for i in ids), key=lambda q: q.pop)
                return p.name, p.lat, p.lon
        return None

    def parse(self, text: str) -> list[dict]:
        if "уражен" not in text.lower():
            return []
        out = []
        for m in BULLET.finditer(text):
            obj, place = m.group(1).strip(" .:-—"), m.group(2)
            lo_obj = obj.lower()
            what = next((label for k, label in WHAT if k in lo_obj), None)
            if not what:
                continue
            loc = self.locate(place)
            if not loc:
                continue
            out.append({"what": what, "detail": obj[:140], "place": loc[0], "lat": loc[1], "lon": loc[2]})
        return out

    def state(self) -> list[dict]:
        now = time.time()
        return [e for e in self.events if now - e["t"] < 72 * 3600]

    async def run(self) -> None:
        async with httpx.AsyncClient(timeout=20, headers=UA, follow_redirects=True) as cli:
            while True:
                try:
                    r = await cli.get(f"https://t.me/s/{CHANNEL}")
                    for mid, ts, text in parse_page(r.text):
                        link = f"https://t.me/{CHANNEL}/{mid}"
                        if link in self.seen:
                            continue
                        self.seen.add(link)
                        for ev in self.parse(text):
                            ev.update(t=ts, link=link)
                            self.events.append(ev)
                    self.events = self.state()
                except Exception as e:  # noqa: BLE001
                    log.warning("strikes: %s", e)
                await asyncio.sleep(600)
