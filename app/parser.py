        # зведення «3 на Дніпропетровщині – Тернівка (1), Шахтарське (1)» — це ПОТОЧНІ місця з кількістю, а не маршрут
        lines = []
        for ln in text.split("\n"):
            if CREDIT.match(ln.strip()):
                continue  # 08.11: «Відео/фото: Труха, СТО Харків» — підпис авторів, а не місце цілі
            bare = ln.strip().rstrip(".")
            # «11 Ударных БпЛА в области. Безлюдовка, Довжик, Первомайский, Дружба, Шевченково.» (Радар Харків 03.11):
            # загальна кількість по області й перелік, де вони зараз. Не одна група ×11 з маршрутом через 5 пунктів
            pm = OBL_SUM.match(bare)
            if pm:
                bare = pm.group(1)
            items = [x.strip() for x in bare.split(",")]
            if len(items) >= 3 and all(LISTITEM.match(x) for x in items):
                # «Чорнобай, Білики, Юріївка, Очаків, Вилкове» — перелік, де цілі зараз, а не маршрут через пів країни
                lines += [f"{POS_MARK}1 {x}" for x in items]
                continue
            m = SUMLINE.match(ln.strip())
            if m:
                # «Київ (1, повз Козин)», «Очаків (1, з акваторії Чорного моря)» — пояснення після кількості
                for name, cnt in re.findall(r"([А-ЯІЇЄҐ][\w'’ʼ\- ]{1,40}?)\s*\((\d+)(?:,[^)]*)?\)", m.group(3)):
                    lines.append(f"{POS_MARK}{cnt} {name.strip()} ({m.group(1)}{m.group(2)})")
            else:
                lines.append(ln)
        if len(lines) != len(text.split("\n")) or any(x.startswith(POS_MARK) for x in lines):
            return [x for x in lines if x.startswith(POS_MARK)] + [s_ for s_ in self.segments("\n".join(x for x in lines if not x.startswith(POS_MARK))) if s_.strip()] if any(not x.startswith(POS_MARK) and x.strip() for x in lines) else [x for x in lines if x.startswith(POS_MARK)]
        loc = None
        plane_hdr = False
        parts = [(r or "").strip(" \t-•–—") for r in SEG_SPLIT.split(text)]
        # «Кропивницький - групи БпЛА (Герань-2/Гербера-2) на місто.» (war_monitor 04.11): назва міста, тире, опис з малої —
        # одне повідомлення, а не «місто без цілі» + «ціль без місця»
        merged = []
        for seg in parts:
            # 08.11: «Київ:\nРеактивний БпЛА курсом на Харківський масив» (Куди летить): місто з двокрапкою окремим рядком —
            # заголовок наступного рядка. Окремо воно ставило «реактивний над центром Києва/Житомира», а рядок без міста
            # вів ціль на Харків замість Харківського масиву Києва
            if merged and seg and CITY_HDR.match(merged[-1]) and not HEADER.match(merged[-1]):
                # «❗️Вінниця:\n⚠️Ракета Герань-5 над Лука-Мелешківська…» (MU): рядок сам називає, де ціль, — місто-заголовок не потрібне
                own = any(r.role == "p" for r in self.parse(seg).places)
                merged[-1] = seg if own else merged[-1] + " " + seg
            elif merged and seg and seg[:1].islower() and merged[-1] and len(merged[-1].split()) <= 3 \
                    and not re.search(r"\d", merged[-1]) and not HEADER.match(merged[-1]):
                merged[-1] = merged[-1] + ": " + seg
            else:
                merged.append(seg)
        for seg in merged:
            if not seg:
                continue
            m = HEADER.match(seg)
            if m:
                header = m.group(1)
                # «✈️Сумщина:» (Куди летить, 04.11): значок літака в заголовку — це ударні БпЛА (шахеди), не «Бандеролі»
                plane_hdr = "✈" in seg[:m.start(1)]
                seg = seg[m.end():].strip()
                if not seg:
                    continue
            if plane_hdr and not TYPE_ANY.search(norm(seg)):
                seg = "БпЛА " + seg
            # «⚠️ На Дніпропетровщині реактивний… ⚠️ 4х БпЛА курсом на Покровське» — область з попереднього пункту
            # зведення діє й на наступні, доки не названо іншу (UkraineRadar_24_7 та подібні)
            lm = LOC_OBL.search(seg)
            if lm:
                loc = lm.group(1)
            elif loc and not header and not REGION_ANY.search(seg):
                seg = f"{seg} ({loc})"
            out.append(f"{seg} ({header})" if header else seg)
        return out or [text]

