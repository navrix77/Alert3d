    def _compact(self, found, bbox, lim_km: float = 25.0):
        """Точка, біля якої є тезка кожної названої в повідомленні назви (середня відстань ≤ lim_km), або None."""
        import math
        P = self.gaz.places
        groups = []
        for _, ids in found:
            ids = [i for i in ids if not bbox or bbox[0] <= P[i].lat <= bbox[1] and bbox[2] <= P[i].lon <= bbox[3]] or ids
            big = [i for i in ids if P[i].pop >= 20000]
            if big:  # «із Запоріжжя на Солоне»: місто важить більше за село-тезку, кластер будуємо від міста
                ids = big
            if len(ids) > 60:
                return None
            groups.append(ids)
        if len({tuple(g) for g in groups}) < 2:
            return None

        def d(a, b):
            return math.hypot((P[a].lat - P[b].lat) * 111, (P[a].lon - P[b].lon) * 72)
        sc = []
        for gi, g in enumerate(groups):
            for a in g:
                others = [min(d(a, b) for b in h) for hj, h in enumerate(groups) if hj != gi and set(h) != set(g)]
                if others:
                    sc.append((sum(others) / len(others), a))
        if not sc:
            return None
        sc.sort()
        m1, a1 = sc[0]
        # інший, віддалений (>50 км) кластер майже такий самий щільний — неоднозначно, не вгадуємо
        m2 = next((m for m, a in sc[1:] if d(a, a1) > 50), None)
        if m1 <= lim_km and (m2 is None or m2 >= max(2 * m1, m1 + 15)):
            return (P[a1].lat, P[a1].lon)
        return None

    def _hdr_filter(self, found):
        """Заголовок «Зпрж:/Днпр:/Кроп:…» (HDR_ABBR): лише тезки в його області або до 60 км від неї; далі обирає звичайна
        логіка (без «регіону каналу», щоб не змінювати вибір серед тезок усередині області: Томаківка, Юріївка)."""
        hdr_bb = getattr(self, "_hdr_bb", None)
        if not hdr_bb:
            return found
        import math
        P = self.gaz.places
        hb = hdr_bb[1]

        def _off(i):
            q = P[i]
            return math.hypot(max(hb[1] - q.lat, 0, q.lat - hb[3]) * 111, max(hb[0] - q.lon, 0, q.lon - hb[2]) * 72)
        from .geo import oblasts as _ob

        def _inpoly(i):
            return _ob().of(P[i].lon, P[i].lat) == hdr_bb[0]

        def _in(i):
            # тезка у своїй області, що не за грубою лінією фронту на півдні (FRONT_PTS; для ланцетів/FPV/КАБ запас 15 км,
            # для решти 5): лише така є підставою відкинути тезку сусідньої області. Запорізьке Покровське на окупованому
            # півдні не «перемагає» Покровське Дніпропетровщини біля межі. Тезки в самій області не відкидаються ніколи
            # (цілі заходять і з півдня: «Реактивний від Михайлівки повернув через Приморське на Запоріжжя»)
            q = P[i]
            return _inpoly(i) and not _south_of_front(q.lat, q.lon, 15.0 if getattr(self, "_typ", None) in FRONTLINE else 5.0)

        def _d(a, b):
            return math.hypot((P[a].lat - P[b].lat) * 111, (P[a].lon - P[b].lon) * 72)
        groups = [[i for i in ids if _off(i) <= 60 or (P[i].kind in ("M", "K") and P[i].pop >= 20000)] for _, ids in found]
        out = []
        for gi, (role, ids) in enumerate(found):
            # лише відкидаємо далекі тезки; місто ≥20 тис. лишається завжди («Днпр+: від Запоріжжя в бік Солоного»)
            ins = groups[gi]
            # 11.11: «Ⓜ️⚔️ Зпрж: Реактивний повз Софіївку на Максимівку» (radar_sich) — та сама фраза в eyes_everywhere_ua
            # дає Софіївку й Максимівку Запорізького району, а в radar_sich ставали Софіївка під Кривим Рогом і Максимівка під
            # Нікополем (у 60-км смузі прямокутника області). Є тезка в самій області заголовка — сусідню не беремо (місто
            # ≥20 тис. лишається). Сусідню лишаємо, якщо поруч (≤25 км, ближче за тезки в області) є тезка іншої назви того ж
            # повідомлення в області заголовка: «Зпрж: Група КАБ через Покровське в бік Новомиколаївки/Софіївки» — Покровське Дніпропетровщини
            # за 23 км від Новомиколаївки Запорізького району, а запорізьке Покровське на окупованому півдні
            near = {j for gj, g in enumerate(groups) if gj != gi and set(g) != set(ins) for j in g if _in(j)}
            own = [k for k in ins if _in(k)]
            inobl = [i for i in ins if _inpoly(i) or (P[i].kind in ("M", "K") and P[i].pop >= 20000)
                     or any(_d(i, j) <= 25 and all(_d(i, j) < _d(k, j) for k in own) for j in near)]
            if inobl and len(inobl) < len(ins) and any(_in(i) for i in inobl):
                ins = inobl
            # тезка сусідньої області біля іншої назви повідомлення проти тезки своєї області лише за лінією фронту: беремо першу
            # (вона ж стає опорою для сусідніх назв: Новомиколаївка біля Покровського, а не ближча до фронту)
            nb = [i for i in ins if not _inpoly(i) and any(_d(i, j) <= 25 for j in near)]
            if nb and own == [] and any(_inpoly(i) for i in ins):
                ins = nb
            if ins:
                out.append((role, ins))
            # інакше: «Кроп:» → Кропи на Львівщині, «Бере курс» → Бір: тезка-слово за сотні км від регіону заголовка
        return out

    def _disambiguate(self, found, bbox, ctx=None, _plain: bool = False) -> list[PlaceRef]:
        import math
        found = self._hdr_filter(found)
        P = self.gaz.places
        self._anchor = None
        uniq = [P[ids[0]] for _, ids in found if len(ids) == 1]
        if uniq:
            cen = (sum(p.lat for p in uniq) / len(uniq), sum(p.lon for p in uniq) / len(uniq))
            if ctx:  # контекст усього повідомлення / недавніх повідомлень каналу
                cen = ((cen[0] + ctx[0]) / 2, (cen[1] + ctx[1]) / 2)
        else:
            # без контексту: КАБ/FPV/«Молнія» б'ють біля фронту («КАБ на Золочів» — Харківщина, не Львівщина)
            cen = ctx or (((bbox[0] + bbox[1]) / 2, (bbox[2] + bbox[3]) / 2) if bbox else (KH if getattr(self, "_typ", None) in FRONTLINE else UA_CENTER))
            # 08.11: усі назви повідомлення мають тезок («Довжик/Рудку», horizon_of_war): якщо одна з тезок кожної назви
            # лежить поруч з іншими (у середньому ≤25 км), це і є місце. Раніше обирався найбільший Довжик області (під
            # Семенівкою, 110 км), хоча Довжик Чернігівського району за 7 км від Рудки
            anchor = self._compact(found, bbox) if len(found) >= 2 and not _plain else None
            if anchor:
                # лише коли звичайний вибір розкидає назви одного повідомлення далі ніж на 60 км у середньому
                dflt = self._disambiguate(found, bbox, ctx, _plain=True)
                pts = [(r.place.lat, r.place.lon) for r in dflt]
                ds = [math.hypot((a[0] - b[0]) * 111, (a[1] - b[1]) * 72) for k, a in enumerate(pts) for b in pts[k + 1:]]
                if not ds or sum(ds) / len(ds) <= 60:
                    return dflt
                cen, uniq = anchor, [None]
                self._anchor = anchor
        out: list[PlaceRef] = []
        bbox0, chan0 = bbox, getattr(self, "_chan_bbox", False)
        for role, ids in found:
            cand = ids
            # позиція («повз», «біля») при області лише як призначенні: шукаємо в регіоні каналу (DEST_OBL)
            pos_role = role == "p" and bool(getattr(self, "_pos_hint", None))
            bbox, self._chan_bbox = (self._pos_bb, True) if pos_role else (bbox0, chan0)
            if bbox:
                inb = [i for i in ids if bbox[0] <= P[i].lat <= bbox[1] and bbox[2] <= P[i].lon <= bbox[3]]
                if not inb and getattr(self, "_chan_bbox", False):
                    # регіональний канал назвав щось, чого в його регіоні немає (острів, урочище, вулиця) —
                    # не «телепортуємо» ціль у тезку за сотні кілометрів
                    def off(i):
                        q = P[i]
                        dy = max(bbox[0] - q.lat, 0, q.lat - bbox[1]) * 111
                        dx = max(bbox[2] - q.lon, 0, q.lon - bbox[3]) * 72
                        return math.hypot(dx, dy)
                    near = [i for i in ids if off(i) <= 60]
                    # але місто за межами регіону ймовірніше за село-тезку біля кордону:
                    # kiev_nebo «повз Гощу на Рівне», «БпЛА на Запоріжжя.», D «БпЛА курсом на Запоріжжя»
                    cities = [i for i in ids if P[i].kind in ("M", "K")]
                    if cities and not any(P[i].kind in ("M", "K") for i in near):
                        near = cities
                    if not near:
                        continue
                    inb = near  # лише тезки біля регіону каналу, а не «найбільший по країні»
                elif not inb:
                    # область названо в самому тексті, а пункту в ній немає: сусідня область — можливо (звідки/куди летить),
                    # але тезка за 150+ км — це помилка: «Глушкове (Полтавщина)» ≠ Глушків на Прикарпатті,
                    # «від Липовця … (Вінниччина)» ≠ Липовиця, «Полтава Сирена» ≠ Сирень у Криму
                    def off(i):
                        q = P[i]
                        dy = max(bbox[0] - q.lat, 0, q.lat - bbox[1]) * 111
                        dx = max(bbox[2] - q.lon, 0, q.lon - bbox[3]) * 72
                        return math.hypot(dx, dy)
                    if getattr(self, "_hint_n", 0) == 1 and not any(off(i) <= 150 for i in ids):
                        continue  # лише коли текст називає одну область («На Вінниччині … На Хмельниччині …» — кілька)
                cand = inb or ids
            _ct = [i for i in ids if i not in cand and P[i].kind in ("M", "K") and P[i].pop >= 20000]
            _h = getattr(self, "_hint", None)
            if _ct and not getattr(self, "_chan_bbox", False) and _h and all(P[i].pop < 5000 for i in cand):
                from .geo import oblasts as _ob
                if not any(_ob().of(P[i].lon, P[i].lat) == _h for i in cand):
                    # 08.11: «БпЛА курсом на Запоріжжя (Харківщина)» — у прямокутнику області лише село-тезка з сусідньої
                    # (Дніпропетровщина), а в самій області пункту немає: місто ймовірніше
                    cand = list(cand) + [i for i in _ct if i not in cand]
            if _ct and all(P[i].kind == "X" and P[i].pop < 5000 for i in cand):
                cand = list(cand) + _ct  # у регіоні з тексту лише хутір-тезка, а відоме місто далі: вирішить score
            hint = getattr(self, "_hint", None)
            if pos_role:
                hint = self._pos_hint
            if hint and len(cand) > 1:
                from .geo import oblasts as _ob
                # точно в області з повідомлення; велике місто поруч (у прямокутнику області) теж лишаємо:
                # «на Лозовую/Днепропетровскую область» — це місто Лозова, а не село Лозове
                inobl = [i for i in cand if _ob().of(P[i].lon, P[i].lat) == hint or P[i].pop >= 20000]
                if inobl:
                    cand = inobl  # точно в області з повідомлення/каналу, а не лише в її прямокутнику
            if hint and getattr(self, "_chan_bbox", False) and not any(P[i].kind in ("M", "K") for i in cand):
                from .geo import oblasts as _ob
                if not any(_ob().of(P[i].lon, P[i].lat) == hint for i in cand):
                    # у регіоні каналу такого пункту немає — місто ймовірніше за село-тезку за кордоном області
                    cities = [i for i in ids if P[i].kind in ("M", "K")]
                    if cities:
                        cand = cities
            import math
            # тезки «місто ≥20 тис. vs село»: без прямої вказівки (район/громада) — це місто.
            # «на Лозову» = місто Лозова, а не село Лозова на Куп'янщині
            # без області в тексті й каналі (bbox немає) — теж: «Суми, Терни, Гадяч, …» (monikppy) — місто Гадяч, а не однойменне село
            big = [i for i in cand if P[i].pop >= 20000 and ((not bbox and getattr(self, "_typ", None) not in FRONTLINE) or bbox and bbox[0] <= P[i].lat <= bbox[1] and bbox[2] <= P[i].lon <= bbox[3])]
            if big and ctx and len(big) < len(cand) and getattr(self, "_chan_bbox", False):
                # 11.11 ніч: «Бандероль на Андреевку … Лиман … Далее курс Сахновщина» (R, KM): за 5 км від щойно названих
                # пунктів є село Лиман (Зміївщина), а місто Лиман на Донеччині за 110 км. Свіжий контекст каналу важить
                # більше за розмір міста, коли місто далеко, а село поруч. Лише для регіональних каналів: у загальних
                # (povitryanatrivogaaa, radar_sich) контекст — інша область, і «→Запоріжжя/р-н» ставав селом на Чернігівщині
                def _dc(i: int) -> float:
                    return math.hypot((P[i].lat - ctx[0]) * 111, (P[i].lon - ctx[1]) * 72)
                if any(_dc(i) <= 25 for i in cand if i not in big) and all(_dc(i) >= 80 for i in big):
                    big = []
            if big and len(big) < len(cand) and all(P[i].pop < 5000 for i in cand if i not in big):
                cand = big

            # відомий місцевим каналам пункт серед тезок своєї області (без контексту сусідніх назв): «над Лісним» у
            # харківських каналах — Лісне з Фельдман Екопарком під Харковом, а не Лісне біля Зміїва (04.11)
            pref = PREFER.get(hint or "", {}).get(P[cand[0]].name) if cand and not ctx and len(found) == 1 else None
            if pref:
                near_ = [i for i in cand if abs(P[i].lat - pref[0]) < 0.03 and abs(P[i].lon - pref[1]) < 0.04]
                if near_:
                    cand = near_
            # 08.11: є однозначний пункт у тому ж повідомленні — тезок обираємо біля нього, а не «найближчу до фронту»
            # («БОМБЫ на Купянск-Узловой, Березовку» — Березівка під Куп'янськом, а не під Золочевом)
            front = not ctx and not uniq and getattr(self, "_typ", None) in FRONTLINE

            anc = getattr(self, "_anchor", None)
            if anc:
                near_a = [i for i in cand if math.hypot((P[i].lat - anc[0]) * 111, (P[i].lon - anc[1]) * 72) <= 40]
                if near_a:
                    cand = near_a

            def score(i: int) -> float:
                p = P[i]
                d = front_km(p.lat, p.lon) if front else math.hypot((p.lat - cen[0]) * 111, (p.lon - cen[1]) * 73)
                # місто (≥20 тис.) майже завжди важливіше за одноіменне село, якщо контекст прямо не вказує на село
                city = (25 if ctx or uniq else 70) if p.pop >= 20000 else 0
                if p.pop >= 20000 and p.kind in ("M", "K") and len(cand) > 1 and all(P[j].kind == "X" and P[j].pop < 5000 for j in cand if j != i):
                    city = 250  # хутір-тезка проти великого міста: «на Павлоград» — це місто, не хутір на Луганщині
                return d - math.log10(1 + p.pop) * (3 if ctx else 6) - city

            if not ctx and not uniq and not bbox and getattr(self, "_typ", None) not in FRONTLINE:
                # жодного контексту (національний канал, перше повідомлення, область не названа): обирає не відстань
                # від умовного центру, а значущість. «ХМЕЛЬНИЦЬКИЙ — відбій червоної тривоги» (zahid_golovne_ua) — місто,
                # а не село на Донеччині; «курсом на Запоріжжя» (KL, MK, K) — місто, а не село під Дніпром;
                # «Затока там ще… бандеролєй» (admiralbukhta) — курортна Затока під Одесою, а не село на Харківщині
                top = max(P[i].pop for i in cand)
                if top >= 2000:
                    cand = [i for i in cand if P[i].pop == top]
            best = min(cand, key=score)
            out.append(PlaceRef(role, P[best]))
        self._chan_bbox = chan0
        return out
