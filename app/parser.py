        dsorted = [r for _, r in sorted(dist_found, key=lambda x: x[0])]
        # 10.11: «мости» в Запоріжжі — майже завжди кінцевий пункт («від Лисогірки до Розумівки, може піти до мостів»,
        # «на Кушугум/Балабине/мости»): ставимо після названих сіл, інакше маршрут починався б з мостів
        late = [r for r in dsorted if r.place.name in LATE_DISTRICTS]
