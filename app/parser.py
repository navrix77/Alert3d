        # довгий новинний текст (звіт ОВА про пошкодження, аналітика, виробництво дронів) без жодного слова про рух —
        # не ціль. Журнал 26.10–02.11: 87 таких «цілей» з 471 довгого повідомлення, усі хибні (SG «у Харківському
        # районі пошкоджено… (сел. Пересічне)», TRK «Серед знайдених компонентів…» → село Середи)
        # умовне «в разі загрози…» — не повідомлення про ціль. Журнал 26.10–02.11: 3 з 3 таких «цілей» хибні
        # (03.11 eRadarrua: «Міхалич, зніми червону тривогу…, щоб в разі загрози балістики…» → «балістика в Михальче»)
        # «над Харковом на П'ятихатки, Сокольники»: місто тут контекст, а не точка в центрі. Позиція «центр міста»
        # давала курс із центру на північ, і та сама ціль ставала двома (03.11, «Ночной Дозор»): прибираємо місто,
