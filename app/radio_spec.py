def render(kind: str, **f) -> str:
    """Текст сповіщення за шаблоном. Поля, яких не передали, не підставляються вигаданими: шаблон без даних повертає порожній рядок."""
    t = TEMPLATES.get(kind)
    if not t:
        return ""
    need = re.findall(r"{(\w+)}", t)
    if any(not str(f.get(k) or "").strip() for k in need):
        return ""
    return t.format(**{k: str(f[k]).strip() for k in need})


_BR1 = re.compile(r"\bNAVRYX\s+SKY\b", re.I)
_BR2 = re.compile(r"\bSKY\b|\bSky\b")


def brand_say(text: str) -> str:
    """Вимова бренду для голосового рушія: NAVRYX SKY → «Наврікс Скай», SKY/Sky → «Скай». Лише для озвучення, не для екрана."""
    t = _BR1.sub("Наврікс Скай", text)
    return _BR2.sub("Скай", t)


def tail(kind: str) -> str:
    """Шаблон без початкового «{obl}. »: для пушів, де назва області вже стоїть у заголовку."""
    return (TEMPLATES.get(kind) or "").replace("{obl}. ", "", 1)
